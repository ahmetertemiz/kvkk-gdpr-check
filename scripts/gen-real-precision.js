#!/usr/bin/env node
/**
 * Generate src/real-precision.js (shipped) from a real-project measurement written by `node bench/real.js --out <file>`.
 *
 *   node scripts/gen-real-precision.js --in <real-results.json> [--out <file>] [--check]
 *
 * The real-project set (bench/real.js) is separate from the 84-project benchmark: hand-verified locations of real
 * applications, judged code first. Only counts are copied, per `source:rule` and `source:sub-signal`: labels the current
 * tool still shows (scored + review; labels it no longer produces are left out), the number of projects with an FP
 * label. No project name, file or label text leaves the private data. Intervals are not copied: src/real-calibration.js
 * computes them, so threshold and data cannot disagree. --check exits 1 when the output would change.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (name, def) => {
  const i = process.argv.indexOf(name);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : def;
};
const IN = arg('--in', null);
const OUT = path.resolve(ROOT, arg('--out', 'src/real-precision.js'));
const CHECK = process.argv.includes('--check');

if (!IN) {
  console.error('usage: node scripts/gen-real-precision.js --in <real-results.json> (the real-project data is private)');
  process.exit(2);
}
const report = JSON.parse(fs.readFileSync(path.resolve(IN), 'utf8'));
const counts = {};
for (const r of [...(report.rules || []), ...(report.subs || [])]) {
  if (/:\(label\)$/.test(r.key)) continue; // labels the tool no longer produces: no sub-signal to describe
  const tp = (r.tp || 0) + (r.tpReview || 0);
  const fp = (r.fp || 0) + (r.fpReview || 0);
  if (!tp && !fp && !r.unc) continue;
  counts[r.key] = { tp, fp, unc: r.unc || 0, fpRepos: (r.fpRepos || []).length };
}
const keys = Object.keys(counts).sort();
const projects = (report.repos || []).filter((x) => !x.error).length;
const body = `// GENERATED by scripts/gen-real-precision.js from a private real-project measurement (bench/real.js). Do not edit.
// Counts only: labels the tool showed (scored + review) per source:rule and source:sub-signal, FP projects.
export const REAL_PROVENANCE = ${JSON.stringify({ tool: report.tool, measured: String(report.at || '').slice(0, 10), projects, live: !!report.live })};

export const REAL_COUNTS = {
${keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(counts[k])},`).join('\n')}
};
`;
if (CHECK) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== body) {
    console.error(`${path.relative(ROOT, OUT)} differs from ${IN}`);
    process.exit(1);
  }
  console.log('real-precision: up to date');
} else {
  fs.writeFileSync(OUT, body);
  console.log(`${path.relative(ROOT, OUT)}: ${keys.length} keys from ${projects} projects`);
}

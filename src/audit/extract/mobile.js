// Push tokens: Expo (getExpoPushTokenAsync / getDevicePushTokenAsync), React Native Firebase / FCM (messaging().getToken(),
// getToken(messaging)), OneSignal / react-native-push-notification registration callbacks are not modelled.
// The token identifies the device installation; where code writes it (a `tokens` collection, a user row) it is stored.
const PUSH_CALL_RE = /\b(getExpoPushTokenAsync|getDevicePushTokenAsync)\s*\(|\bmessaging\s*\(\s*\)\s*\.\s*getToken\s*\(|\bgetToken\s*\(\s*(?:getMessaging\s*\(|messaging\b)/;

function pushCallName(call) {
  const c = unwrap(call?.callee);
  if (!c) return null;
  const nm = c.type === 'Identifier' ? c.name : (c.type === 'MemberExpression' || c.type === 'OptionalMemberExpression') && !c.computed ? c.property?.name : null;
  if (nm === 'getExpoPushTokenAsync' || nm === 'getDevicePushTokenAsync') return nm;
  if (nm === 'getToken') {
    const obj = c.type === 'Identifier' ? null : unwrap(c.object);
    // messaging().getToken() / firebase.messaging().getToken() / getToken(getMessaging(), …) / getToken(messaging, …)
    if (obj?.type === 'CallExpression') {
      const oc = unwrap(obj.callee);
      const on = oc?.type === 'Identifier' ? oc.name : oc?.property?.name;
      if (on === 'messaging') return 'messaging().getToken';
    }
    if (c.type === 'Identifier') {
      const a0 = unwrap(call.arguments?.[0]);
      if (a0 && ((a0.type === 'CallExpression' && /^getMessaging$/.test(unwrap(a0.callee)?.name || '')) || (a0.type === 'Identifier' && /messaging/i.test(a0.name)))) return 'getToken(messaging)';
    }
  }
  return null;
}

/** Push-token device source, its element, and flows into the stores whose writes carry the token. */
function pushTokens(ctx, dead) {
  const { graph, ev } = ctx;
  const files = (ctx.files || []).filter((f) => f && !f.test && JS_EXT.test(f.rel) && !/\.(vue|svelte|astro)$/i.test(f.rel) && !dead.has(f.rel) && PUSH_CALL_RE.test(f.content || ''));
  for (const f of files) {
    const rec = getAst(ctx, f.rel);
    if (!rec) continue;
    astWalk(rec.ast.program, (n, parent, ancestors) => {
      if (n.type !== 'CallExpression') return;
      const api = pushCallName(n);
      if (!api) return;
      const line = lineOf(n);
      const e = ev(f.rel, line, lineText(f.content, line), 'static', 0.85, api);
      const sid = 'source:device:push-token';
      graph.addNode({ id: sid, type: 'Source', kind: 'device', name: 'push-token', permissions: [api], platforms: ['cross-platform'], file: f.rel, line, declared: false, unused: false, reached: [e], evidence: [e] });
      // Its own element (not the generic device id): the token addresses this installation through the push service.
      const did = 'data:push_token';
      graph.addNode({
        id: did, type: 'DataElement', name: 'push_token', category: 'device', sensitivity: 'normal', identifier: 'indirect',
        label: { tr: 'Push bildirim belirteci (cihaz)', en: 'Push notification token (device)' }, aliases: ['push_token'], evidence: [e],
      });
      graph.addEdge({ from: sid, to: did, type: 'collects', evidence: [e] });
      // The push service issues the token and keeps the device registration it addresses (Expo push service for
      // getExpoPushTokenAsync, FCM / APNs for device tokens): its purpose is addressing notifications through that
      // service. The transfer register already lists the SDK's device identifier for push vendors (implied rows).
      const pv = ctx.vendors?.vendorById?.('push');
      if (pv) {
        const vid = graph.vendorSink(pv, e);
        graph.addEdge({ from: did, to: vid, type: 'usedBy', purpose: 'push-delivery', evidence: [ev(f.rel, line, lineText(f.content, line), 'static', 0.8, `${api}: the token addresses this device through the push service`)] });
      }
      // The variable the token lands in: const token = await …; const { data: token } = await …
      const decl = [...ancestors].reverse().find((a) => a.type === 'VariableDeclarator');
      const names = new Set();
      if (decl?.id?.type === 'Identifier') names.add(decl.id.name);
      else if (decl?.id?.type === 'ObjectPattern') for (const p of decl.id.properties) if (p.value?.type === 'Identifier') names.add(p.value.name);
      if (!names.size) return;
      const fn = [...ancestors].reverse().find((a) => /Function/.test(a.type)) || rec.ast.program;
      // Writes in the same function whose object literal carries the token: { token: token.data }, { pushToken: token }.
      astWalk(fn, (m) => {
        if (m.type !== 'ObjectProperty' || (m.start ?? 0) < (n.start ?? 0)) return;
        let v = unwrap(m.value);
        while (v && (v.type === 'MemberExpression' || v.type === 'OptionalMemberExpression')) v = unwrap(v.object);
        if (v?.type !== 'Identifier' || !names.has(v.name)) return;
        const pl = lineOf(m);
        const cols = graph.nodesOf('Store', (s) => s.kind === 'column' && s.file === f.rel && s.line === pl);
        for (const col of cols) {
          const we = ev(f.rel, pl, lineText(f.content, pl), 'static', 0.8, `push token (${api}) written to ${col.table}.${col.column}`);
          graph.addEdge({ from: did, to: col.id, type: 'flowsTo', sourceId: sid, evidence: [e, we] });
          if (!graph.edgesFrom(col.id, 'represents').some((r) => r.to === did)) graph.addEdge({ from: col.id, to: did, type: 'represents', evidence: [we] });
        }
      });
    });
  }
}


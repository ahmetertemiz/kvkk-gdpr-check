// Native / Flutter push registration (r8): Firebase Messaging, APNs and OneSignal in Dart, Kotlin / Java and Swift, and
// OneSignal in JS. The messaging import / class must be in the file: a bare getToken() is as often a session token.
//   dart    package:firebase_messaging/ + FirebaseMessaging…getToken() / onTokenRefresh / onMessage
//   kotlin  com.google.firebase.messaging + FirebaseMessaging.getInstance().token / onNewToken(token)
//   swift   Messaging.messaging().token / didReceiveRegistrationToken / didRegisterForRemoteNotificationsWithDeviceToken
//   any     OneSignal.initialize / setAppId / init
// A token printed to a log is a flow to the log store; a token written under a push-named key is linked to its column.
const PUSH_FILE = /\.(dart|kt|kts|java|swift|m|mm)$/i;
const PUSH_IMPORT = /package:firebase_messaging\/|com\.google\.firebase\.messaging|\bFirebaseMessaging\b|\bMessaging\.messaging\(\)|didRegisterForRemoteNotificationsWithDeviceToken|package:onesignal_flutter\/|com\.onesignal|\bOneSignal(?:Framework)?\b/;
const PUSH_NATIVE = [
  // [extension, call, confidence]
  [/\.dart$/i, /\b(?:FirebaseMessaging\s*\.\s*instance|FirebaseMessaging\(\)|_?\w*[Mm]essaging\w*)\s*\.\s*getToken\s*\(/g, 0.85],
  [/\.dart$/i, /\bonTokenRefresh\b/g, 0.8],
  [/\.(kt|kts|java)$/i, /\bFirebaseMessaging\s*\.\s*getInstance\(\)\s*\.\s*(?:token\b|getToken\s*\()|\bvoid\s+onNewToken\s*\(|\bfun\s+onNewToken\s*\(/g, 0.85],
  [/\.(swift|m|mm)$/i, /\bMessaging\s*\.\s*messaging\(\)\s*\.\s*(?:token\b|fcmToken\b)|didReceiveRegistrationToken|didRegisterForRemoteNotificationsWithDeviceToken/g, 0.85],
];
/** Registration without reading the token: the SDK registers the installation with the push service on its own. */
const PUSH_REGISTER = /\bFirebaseMessaging\s*\.\s*(?:onMessage|onBackgroundMessage|onMessageOpenedApp)\b|\.\s*subscribeToTopic\s*\(|\bOneSignal\s*\.\s*(?:initialize|init|setAppId|initWithContext)\b|\bOneSignal\s*\(\s*["']/g;
const PUSH_LOG = /\b(?:print|debugPrint|log|println|NSLog|os_log|Timber\.\w+|Log\.[vdiwe]|console\.\w+|logger?\.\w+)\s*\(/;
const PUSH_KEY = /['"](\w*(?:push|fcm|expo|apns|device|registration)\w*token\w*|token)['"]\s*:\s*/i;

function stripPushComments(src) {
  return src.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' ')).replace(/^[ \t]*\/\/.*$/gm, (m) => ' '.repeat(m.length));
}

function pushElement(graph, e) {
  const did = 'data:push_token';
  graph.addNode({
    id: did, type: 'DataElement', name: 'push_token', category: 'device', sensitivity: 'normal', identifier: 'indirect',
    label: { tr: 'Push bildirim belirteci (cihaz)', en: 'Push notification token (device)' }, aliases: ['push_token'], evidence: [e],
  });
  return did;
}

function logFlow(ctx, f, line, sid, api, e) {
  const { graph, ev } = ctx;
  const le = ev(f.rel, line, lineText(f.content, line), 'static', 0.8, `push token (${api}) printed to the device log`);
  const lid = 'store:log:console';
  if (!graph.node(lid)) graph.addNode({ id: lid, type: 'Store', kind: 'log', name: 'console', evidence: [le] });
  graph.addEdge({ from: 'data:push_token', to: lid, type: 'flowsTo', sourceId: sid, evidence: [le, e].filter(Boolean) });
}

function nativePush(ctx) {
  const { graph, ev } = ctx;
  for (const f of ctx.files || []) {
    if (!f || f.test || typeof f.content !== 'string' || f.content.length > 400_000) continue;
    const native = PUSH_FILE.test(f.rel);
    const jsOneSignal = JS_EXT.test(f.rel) && /['"](?:react-native-onesignal|react-onesignal|onesignal-cordova-plugin)['"]/.test(f.content);
    if (!(native && PUSH_IMPORT.test(f.content)) && !jsOneSignal) continue;
    const src = stripPushComments(f.content);
    const lines = src.split(/\r?\n/);
    const hits = [];
    for (const [ext, re, conf] of PUSH_NATIVE) {
      if (!ext.test(f.rel)) continue;
      for (const m of src.matchAll(re)) hits.push({ idx: m.index, api: m[0].replace(/\s+/g, '').replace(/\($/, ''), conf, reads: true });
    }
    if (!hits.length) {
      const m = [...src.matchAll(PUSH_REGISTER)][0];
      if (m) hits.push({ idx: m.index, api: m[0].replace(/\s+/g, ''), conf: 0.6, reads: false });
    }
    if (!hits.length) continue;
    const h = hits[0];
    const line = lineAt(src, h.idx);
    const e = ev(f.rel, line, lineText(f.content, line), 'static', h.conf, h.api);
    const sid = 'source:device:push-token';
    const platform = /\.(kt|kts|java)$/i.test(f.rel) ? 'android' : /\.(swift|m|mm)$/i.test(f.rel) ? 'ios' : 'cross-platform';
    graph.addNode({ id: sid, type: 'Source', kind: 'device', name: 'push-token', permissions: [h.api], platforms: [platform], file: f.rel, line, declared: false, unused: false, reached: [e], evidence: [e] });
    const did = pushElement(graph, e);
    graph.addEdge({ from: sid, to: did, type: 'collects', evidence: [e] });
    const pv = ctx.vendors?.vendorById?.('push');
    if (pv) {
      const vid = graph.vendorSink(pv, e);
      graph.addEdge({ from: did, to: vid, type: 'usedBy', purpose: 'push-delivery', evidence: [ev(f.rel, line, lineText(f.content, line), 'static', 0.8, `${h.api}: the token addresses this device through the push service`)] });
    }
    for (const x of hits.filter((y) => y.reads)) {
      const l0 = lineAt(src, x.idx);
      const win = lines.slice(l0 - 1, l0 + 24);
      const head = `${lines[l0 - 2] || ''}\n${win.slice(0, 3).join('\n')}`;
      // Where the token lands: .then((token) {…, final t = await …, onNewToken(token: String), { fcmToken in …
      const tok = /\.then\(\s*\(?\s*(?:String\??\s+)?(\w+)\s*\)?\s*(?:async\s*)?(?:\{|=>)/.exec(head)?.[1]
        || /(?:final|var|let|val|const|String\??)\s+(\w+)\s*=\s*(?:try\s+)?(?:await\s+)?[^;\n]*(?:getToken|\.token)/.exec(head)?.[1]
        || /onNewToken\s*\(\s*(?:@NonNull\s+)?(?:final\s+)?(?:String\s+)?(\w+)/.exec(head)?.[1]
        || /didReceiveRegistrationToken\s+(\w+)/.exec(head)?.[1]
        || /didRegisterForRemoteNotificationsWithDeviceToken\s+(\w+)/.exec(head)?.[1]
        || /\.listen\(\s*\(?\s*(\w+)/.exec(head)?.[1];
      if (!tok || /^(?:err|error|e|_)$/.test(tok)) continue;
      const use = new RegExp(`\\b${tok}\\b`);
      for (let i = 0; i < win.length; i++) {
        const t = win[i];
        if (i > 0 && /^\s{0,2}(?:@override|override\s+fun|func\s|void\s|Future<|fun\s|private\s|public\s)/.test(t)) break;
        const at = l0 + i;
        const lm = PUSH_LOG.exec(t);
        if (lm && use.test(t.slice(lm.index + lm[0].length))) logFlow(ctx, f, at, sid, x.api, e);
        const k = PUSH_KEY.exec(t);
        if (k && new RegExp(`:\\s*\\[?\\s*${tok}\\b`).test(t)) {
          const key = k[1].replace(/_/g, '').toLowerCase();
          const cols = graph.nodesOf('Store', (s) => s.kind === 'column' && String(s.column || '').replace(/_/g, '').toLowerCase() === key && (key !== 'token' || s.file === f.rel));
          if (cols.length === 1) {
            const we = ev(f.rel, at, lineText(f.content, at), 'static', 0.75, `push token (${x.api}) written to ${cols[0].table}.${cols[0].column}`);
            graph.addEdge({ from: did, to: cols[0].id, type: 'flowsTo', sourceId: sid, evidence: [e, we] });
            if (!graph.edgesFrom(cols[0].id, 'represents').some((r) => r.to === did)) graph.addEdge({ from: cols[0].id, to: did, type: 'represents', evidence: [we] });
          }
        }
      }
    }
  }
}

/** JS / TS push tokens (pushTokens above) that are printed: console.log(token) in the function that reads the token. */
function pushTokenLogs(ctx, dead) {
  const { graph } = ctx;
  if (!graph.node('data:push_token')) return;
  for (const f of ctx.files || []) {
    if (!f || f.test || !JS_EXT.test(f.rel) || dead.has(f.rel) || !PUSH_CALL_RE.test(f.content || '')) continue;
    const src = stripPushComments(f.content);
    const m = PUSH_CALL_RE.exec(src);
    if (!m) continue;
    const l0 = lineAt(src, m.index);
    const lines = src.split(/\r?\n/);
    const head = lines.slice(Math.max(0, l0 - 3), l0 + 2).join('\n');
    const tok = /(?:const|let|var)\s+(?:\{\s*data\s*:\s*(\w+)|(\w+))[^=\n]*=\s*(?:\(\s*)?await/.exec(head)?.slice(1).find(Boolean)
      || /\.then\(\s*\(?\s*(\w+)/.exec(head)?.[1] || /(\w+)\s*=\s*\(?\s*await\s+[^\n]*(?:PushToken|getToken)/.exec(head)?.[1];
    if (!tok) continue;
    const re = new RegExp(`\\bconsole\\.\\w+\\s*\\([^;\\n]*\\b${tok}\\b(?!\\s*(?:===?|!==?))`);
    for (let i = l0; i < Math.min(lines.length, l0 + 25); i++) {
      if (!re.test(lines[i])) continue;
      const known = graph.edgesFrom('data:push_token', 'flowsTo').some((x) => x.evidence?.some((y) => y.file === f.rel && y.line === i + 1));
      if (!known) logFlow(ctx, f, i + 1, 'source:device:push-token', 'push token', null);
      break;
    }
  }
}

export function extract(ctx) {
  const { graph, ev, files } = ctx;
  const hits = new Map(); // kind → [{file, line, snippet, via, platform}]
  const add = (kind, h) => {
    if (!hits.has(kind)) hits.set(kind, []);
    hits.get(kind).push(h);
  };

  for (const f of files) {
    const isManifest = /AndroidManifest\.xml$/.test(f.rel);
    const isPlist = /\.(plist|entitlements)$/.test(f.rel);
    const isAppConfig = /(^|\/)app\.(json|config\.(js|ts))$/.test(f.rel);
    const isPkg = f.kind === 'manifest';
    if (!isManifest && !isPlist && !isAppConfig && !isPkg) continue;
    const lines = f.content.split(/\r?\n/);
    lines.forEach((ln, i) => {
      for (const [kind, d] of Object.entries(DEVICE)) {
        if (isManifest || isAppConfig) {
          for (const p of d.android) {
            const re = new RegExp(`(android\\.permission\\.|["'])${p.replace('.', '\\.')}\\b`);
            if (re.test(ln)) add(kind, { file: f.rel, line: i + 1, snippet: ln.trim(), via: p, platform: 'android' });
          }
        }
        if (isPlist || isAppConfig) {
          for (const k of d.ios) if (ln.includes(k)) add(kind, { file: f.rel, line: i + 1, snippet: ln.trim(), via: k, platform: 'ios' });
        }
        if (isPkg || isAppConfig) {
          for (const pl of d.expo) if (new RegExp(`["']${pl}["']`).test(ln)) add(kind, { file: f.rel, line: i + 1, snippet: ln.trim(), via: pl, platform: 'cross-platform' });
        }
      }
    });
  }

  let dead = new Set();
  let reach = null;
  try {
    dead = deadModules(ctx);
    reach = evaluateReach(ctx, dead);
  } catch (e) {
    ctx.warn?.(`mobile: reachability check skipped (${e.message})`);
    reach = null;
  }

  // Web capture (getUserMedia) → device sources with platform 'web' (only when no manifest declared them).
  const webAudio = (reach?.captures || []).filter((c) => c.audio);
  const webVideo = (reach?.captures || []).filter((c) => c.video);
  const webHit = (c, via) => ({ file: c.f.rel, line: lineAt(c.f.content, c.index), snippet: lineText(c.f.content, lineAt(c.f.content, c.index)), via, platform: 'web' });
  const webOnly = new Set();
  if (webAudio.length && !hits.has('microphone')) {
    webAudio.forEach((c) => add('microphone', webHit(c, 'getUserMedia(audio)')));
    webOnly.add('microphone');
  }
  if (webVideo.length && !hits.has('camera')) {
    webVideo.forEach((c) => add('camera', webHit(c, 'getUserMedia(video)')));
    webOnly.add('camera');
  }

  for (const [kind, list] of hits) {
    const d = DEVICE[kind];
    const id = `source:device:${kind}`;
    const evidence = list.slice(0, 10).map((h) => ev(h.file, h.line, h.snippet, 'static', h.platform === 'cross-platform' ? 0.6 : 0.9));
    const declared = list.some((h) => h.platform === 'android' || h.platform === 'ios');
    const evaluated = !!reach && !!REACH[kind] && (reach.mobileClient || list.every((h) => h.platform === 'web'));
    const reachedEv = evaluated ? reach.reached.get(kind) || [] : [];
    const unused = evaluated ? reachedEv.length === 0 : undefined;
    graph.addNode({
      id, type: 'Source', kind: 'device', name: kind, permissions: [...new Set(list.map((h) => h.via))], platforms: [...new Set(list.map((h) => h.platform))],
      file: list[0].file, line: list[0].line, ...(d.onDevice ? { onDevice: true } : {}), evidence,
      declared,
      ...(evaluated ? { unused } : {}),
      ...(reachedEv.length ? { reached: reachedEv } : {}),
      ...(unused ? {
        unusedReason: {
          tr: 'İzin/kütüphane tanımlı ama canlı kodda bu yeteneği kullanan bir API çağrısı yok (hiç import edilmeyen modüller sayılmadı)',
          en: 'Permission/library declared but no live code calls an API that uses it (modules nobody imports were excluded)',
        },
      } : {}),
    });
    // A package-only hit whose API is never reached collects nothing; web capture collects only when linked below.
    if (unused && !declared) continue;
    if (webOnly.has(kind)) continue;
    // Declared but never reached: the permission grants access the app does not use. It collects the access itself
    // (a dedicated element nothing uses, so minimisation reports the permission), and the generic data a live capture
    // would produce is kept on edges flagged declaredOnly (a camera permission next to a gallery picker does not make
    // photos camera captures).
    // Fine and coarse location share one reach model: a declared fine-location permission already reports the access.
    const coveredByFine = kind === 'approx-location' && (hits.get('location') || []).some((h) => h.platform === 'android' || h.platform === 'ios');
    if (unused && declared && !d.onDevice && KIND_LABEL[kind] && !coveredByFine) {
      const generic = d.elements.find((x) => !x.startsWith('@'));
      const gcls = generic ? ctx.classify(generic) : null;
      const el = `${kind.replace(/-/g, '_')}_access`;
      const did = `data:${el}`;
      graph.addNode({
        id: did, type: 'DataElement', name: el, category: gcls?.category || CUSTOM[(d.elements[0] || '').slice(1)]?.category || 'device', sensitivity: gcls?.sensitivity === 'special' ? 'special' : 'normal',
        identifier: 'none', declaredOnly: true,
        label: { tr: `${KIND_LABEL[kind].tr} erişimi (izin tanımlı)`, en: `${KIND_LABEL[kind].en} access (permission declared)` },
        aliases: [...new Set(list.map((h) => h.via))], evidence: [evidence[0]],
      });
      // Its own source node (the permission declaration), so the capability source keeps its generic contract.
      const pid = `${id}:declared`;
      graph.addNode({ id: pid, type: 'Source', kind: 'device', name: kind, permissions: [...new Set(list.map((h) => h.via))], file: list[0].file, line: list[0].line, declared: true, unused: true, declaredOnly: true, of: id, evidence });
      graph.addEdge({ from: pid, to: did, type: 'collects', declaredOnly: true, evidence });
    }
    for (const spec of d.elements) {
      const did = elementId(ctx, spec, evidence[0]);
      if (did) graph.addEdge({ from: id, to: did, type: 'collects', ...(unused && declared ? { declaredOnly: true } : {}), evidence });
    }
  }

  // Voice reaching an AI model: microphone captured by live code + an AI sink whose code streams/transcribes audio.
  const mic = graph.node('source:device:microphone');
  if (mic && mic.unused === false) {
    const targets = voiceAiSinks(ctx, dead);
    if (targets.length) {
      const capEv = mic.reached?.[0] || mic.evidence?.[0];
      const vid = elementId(ctx, 'voice', capEv);
      if (vid) {
        graph.addEdge({ from: mic.id, to: vid, type: 'collects', evidence: [capEv] });
        for (const { sink, evidence } of targets) {
          graph.addEdge({ from: vid, to: sink.id, type: 'flowsTo', sourceId: mic.id, channel: 'audio-stream', evidence: [capEv, evidence].filter(Boolean) });
        }
      }
    }
  }

  try {
    pushTokens(ctx, dead);
    nativePush(ctx);
    pushTokenLogs(ctx, dead);
  } catch (e) {
    ctx.warn?.(`mobile: push tokens: ${e.message}`);
  }
  try {
    platformConfigVendors(ctx);
  } catch (e) {
    ctx.warn?.(`mobile: platform config: ${e.message}`);
  }

  // Annotate (never remove) edges that only dead modules produced.
  if (dead.size) {
    for (const e of graph.edges) {
      if (!['flowsTo', 'readBy', 'usedBy', 'exposes'].includes(e.type)) continue;
      const evs = (e.evidence || []).filter((x) => x?.file);
      if (evs.length && evs.every((x) => dead.has(x.file))) e.deadCode = true;
    }
  }

  if (hits.size) ctx.shared.deviceSources = [...hits.keys()].map((k) => `source:device:${k}`);
}

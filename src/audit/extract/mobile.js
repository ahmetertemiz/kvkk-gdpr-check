// Platform configuration as vendor evidence (r6 WS4)
//
// Firebase platform files are generated by the Firebase console / FlutterFire CLI and only exist when the app is wired to
// a Firebase project: android google-services.json, iOS/macOS GoogleService-Info.plist, firebase.json (with a firestore /
// database / storage / functions section) and .firebaserc. They make the Firebase sink (static, confidence 0.6) and give
// its region when a Realtime Database URL names one (…europe-west1.firebasedatabase.app) or firebase.json states a
// Firestore location. Credential values in these files (api_key, client_id …) are never copied: evidence snippets are
// synthetic ("google-services.json: Firebase Android configuration").
// A Firebase sink is created from these files only when no other managed backend (Supabase, Appwrite …) is in the graph:
// an app on another backend often keeps google-services.json for push (FCM) alone. Otherwise they only add evidence to an
// existing Firebase sink.
const OTHER_BACKENDS = /^(supabase|appwrite|neon|planetscale|mongodb-atlas|turso|cockroachdb|aiven|convex|clerk)$/;
const FIRESTORE_LOCATION = [[/^(eur3|europe-|eu)/i, 'EU'], [/^(nam5|nam7|us-|northamerica-)/i, 'US'], [/^asia-|^australia-/i, 'APAC']];

function platformConfigVendors(ctx) {
  const { graph, ev } = ctx;
  const fb = ctx.vendors?.vendorById?.('firebase');
  if (!fb) return;
  const found = []; // {rel, line, snippet, hosts:[], location, strong}
  for (const f of ctx.files || []) {
    if (f.test) continue;
    const base = nodePath.posix.basename(f.rel);
    const content = f.content.replace(/\r\n?/g, '\n');
    const lineOfText = (re) => {
      const m = re.exec(content);
      return m ? content.slice(0, m.index).split('\n').length : 1;
    };
    if (base === 'google-services.json') {
      let j = null;
      try {
        j = JSON.parse(content);
      } catch {
        continue;
      }
      if (!j?.project_info || !Array.isArray(j.client)) continue;
      const hosts = [j.project_info.firebase_url].filter((u) => typeof u === 'string');
      found.push({ rel: f.rel, line: lineOfText(/"project_info"/), snippet: 'google-services.json: Firebase Android configuration (api_key AIza_[REDACTED])', hosts, strong: true });
    } else if (/^GoogleService-Info\.plist$/.test(base)) {
      if (!/<key>\s*(GOOGLE_APP_ID|PROJECT_ID)\s*<\/key>/.test(content)) continue;
      const db = /<key>\s*DATABASE_URL\s*<\/key>\s*<string>\s*([^<\s]+)\s*<\/string>/.exec(content);
      found.push({ rel: f.rel, line: lineOfText(/<key>\s*(PROJECT_ID|GOOGLE_APP_ID)\s*<\/key>/), snippet: 'GoogleService-Info.plist: Firebase iOS configuration (API_KEY AIza_[REDACTED])', hosts: db ? [db[1]] : [], strong: true });
    } else if (base === 'firebase.json') {
      let j = null;
      try {
        j = JSON.parse(content);
      } catch {
        continue;
      }
      if (!j || typeof j !== 'object') continue;
      const data = ['firestore', 'database', 'storage', 'functions'].filter((k) => j[k]);
      if (!data.length) continue; // Hosting alone serves the site; it says nothing about where data is kept
      const fsCfg = Array.isArray(j.firestore) ? j.firestore[0] : j.firestore;
      found.push({ rel: f.rel, line: lineOfText(new RegExp(`"${data[0]}"`)), snippet: `firebase.json: ${data.join(', ')} configured`, hosts: [], location: typeof fsCfg?.location === 'string' ? fsCfg.location : null, strong: true });
    }
  }
  // .firebaserc (no extension, so the walker does not list it): project aliases only — supporting evidence.
  if (ctx.root) {
    try {
      const p = nodePath.join(ctx.root, '.firebaserc');
      if (fs.existsSync(p) && fs.statSync(p).size < 64 * 1024 && /"projects"\s*:/.test(fs.readFileSync(p, 'utf8'))) found.push({ rel: '.firebaserc', line: 1, snippet: '.firebaserc: Firebase project alias', hosts: [], strong: false });
    } catch {
      /* unreadable */
    }
  }
  if (!found.length) return;
  const id = `sink:vendor:${fb.id}`;
  const exists = graph.has(id);
  const otherBackend = graph.nodesOf('Sink', (n) => n.kind === 'vendor' && OTHER_BACKENDS.test(n.vendorId || '')).length > 0;
  if (!exists && (otherBackend || !found.some((x) => x.strong))) return;
  for (const x of found) {
    const e = ev(x.rel, x.line, x.snippet, 'static', 0.6, 'Firebase platform configuration');
    graph.vendorSink(fb, e);
    const node = graph.node(id);
    if (!exists && !node.detectedBy) node.detectedBy = 'platform-config';
    for (const h of x.hosts) {
      let host = null;
      try {
        host = new URL(h).hostname;
      } catch {
        host = null;
      }
      const r = host ? regionForHost(host) : null;
      if (r?.region && !node.region) {
        node.region = r.region;
        if (/bölge|region|\//i.test(node.country || '') && r.source !== 'cctld') node.regionCountry = r.country;
        node.regionSource = x.rel;
      }
    }
    if (x.location && !node.region) {
      const hit = FIRESTORE_LOCATION.find(([re]) => re.test(x.location));
      node.region = x.location;
      if (hit && /bölge|region|\//i.test(node.country || '')) node.regionCountry = hit[1];
      node.regionSource = x.rel;
    }
  }
}


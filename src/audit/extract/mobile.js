function elementId(ctx, spec, e) {
  const { graph } = ctx;
  if (spec.startsWith('@')) {
    const c = CUSTOM[spec.slice(1)];
    const id = `data:${c.element}`;
    graph.addNode({ id, type: 'DataElement', name: c.element, category: c.category, sensitivity: c.sensitivity, identifier: c.identifier, label: c.label, ...(c.thirdParty ? { thirdPartyData: true } : {}), aliases: [], evidence: [e] });
    return id;
  }
  const cls = ctx.classify(spec);
  return cls ? graph.dataElement(cls, null, e) : null;
}

/** getUserMedia call sites with the requested media kinds (literal constraints; unknown → both). */
function mediaCaptures(content) {
  const out = [];
  const re = /\bgetUserMedia\s*\(/g;
  let m;
  while ((m = re.exec(content))) {
    const win = content.slice(m.index, m.index + 400);
    const lit = /^getUserMedia\s*\(\s*\{/.test(win);
    let audio;
    let video;
    if (lit) {
      audio = /\baudio\s*:\s*(?!false\b)/.test(win);
      video = /\bvideo\s*:\s*(?!false\b)/.test(win);
    } else {
      audio = /\baudio\s*:\s*(?!false\b)/.test(content);
      video = /\bvideo\s*:\s*(?!false\b)/.test(content);
      if (!audio && !video) audio = video = true;
    }
    out.push({ index: m.index, audio, video });
  }
  return out;
}

// Code that streams or transcribes audio to an AI model (realtime/live sessions, speech-to-text endpoints).
const VOICE_AI_MARKER = /\b(getUserMedia|connectLive|sendRealtimeInput|inputAudioTranscription|input_audio_transcription|input_audio_buffer|audio\.transcriptions|audio\.translations|createTranscription|transcribeAudio|speechToText|speech_to_text|SpeechClient|RealtimeClient|RealtimeAgent|RealtimeSession|realtime\.connect|live\.connect)\b|\b(gpt-4o(-mini)?-(realtime|transcribe|audio)[\w.-]*|gpt-realtime[\w.-]*|whisper-1|(gemini|gpt|openai\/gpt)[\w.-]*-live\b[\w.-]*|[\w.-]*native-audio[\w.-]*)/i;

function evaluateReach(ctx, dead) {
  const files = (ctx.files || []).filter((f) => f && typeof f.rel === 'string' && typeof f.content === 'string' && !f.test);
  if (files.some((f) => UNMODELLED_CLIENT_EXT.test(f.rel))) return null;
  // Config files and Expo config plugins name permissions without using them.
  const live = files.filter((f) => CLIENT_EXT.test(f.rel) && !dead.has(f.rel) && !CONFIG_FILE.test(f.rel) && !CONFIG_PLUGIN.test(f.content));
  if (!live.length) return null;
  const reached = new Map(); // kind → Evidence[]
  const push = (kind, f, idx, note) => {
    if (!reached.has(kind)) reached.set(kind, []);
    const list = reached.get(kind);
    if (list.length >= 5) return;
    const line = lineAt(f.content, idx);
    list.push(ctx.ev(f.rel, line, lineText(f.content, line), 'static', 0.8, note));
  };
  const captures = [];
  for (const f of live) {
    const specs = /\.(dart|jsx?|tsx?|mjs|cjs|vue|svelte|astro)$/i.test(f.rel) ? specifiers(f.content) : [];
    for (const [kind, r] of Object.entries(REACH)) {
      const a = r.api.exec(f.content);
      if (a) push(kind, f, a.index, a[0]);
      const lib = specs.find((s) => r.libs.test(s) || (HYBRID_PLUGIN.test(s) && PLUGIN_WORD[kind]?.test(s)));
      if (lib) push(kind, f, f.content.indexOf(lib), lib);
      if (r.calls) {
        const vc = specs.find((s) => VIDEO_CALL_LIBS.test(s));
        if (vc) push(kind, f, f.content.indexOf(vc), vc);
      }
    }
    if (JS_EXT.test(f.rel) || /\.html?$/i.test(f.rel)) {
      for (const c of mediaCaptures(f.content)) {
        captures.push({ f, ...c });
        if (c.audio) push('microphone', f, c.index, 'getUserMedia(audio)');
        if (c.video) push('camera', f, c.index, 'getUserMedia(video)');
      }
    }
  }
  // Code we can read must include the mobile client itself (RN/Expo/Flutter/native/hybrid); otherwise a
  // manifest next to, say, a Node backend says nothing about where the capability is used.
  const mobileClient = live.some((f) => /\.(dart|kt|kts|java|swift)$/i.test(f.rel)) ||
    files.some((f) => /(^|\/)package\.json$/.test(f.rel) && MOBILE_DEP.test(f.content));
  return { reached, captures, mobileClient };
}

/** AI vendor sinks whose (live) code streams or transcribes audio; returns [{sink, evidence}]. */
function voiceAiSinks(ctx, dead) {
  const { graph } = ctx;
  const byRel = new Map((ctx.files || []).map((f) => [f.rel, f]));
  const out = [];
  for (const s of graph.nodesOf('Sink', (n) => n.kind === 'vendor' && n.category === 'ai')) {
    for (const e of s.evidence || []) {
      const f = e?.file && byRel.get(e.file);
      if (!f || f.test || dead.has(f.rel) || typeof f.content !== 'string') continue;
      const m = VOICE_AI_MARKER.exec(f.content);
      if (!m) continue;
      const line = lineAt(f.content, m.index);
      out.push({ sink: s, evidence: ctx.ev(f.rel, line, lineText(f.content, line), 'static', 0.7, m[0]) });
      break;
    }
  }
  return out;
}


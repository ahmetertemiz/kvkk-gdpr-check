/**
 * Mobile extractor: Android permissions, iOS usage descriptions / entitlements, Expo app.json/app.config
 * → Source nodes `source:device:<kind>` + collects edges.
 *
 * Declared ≠ used. Each declared capability is cross-checked against the capture APIs that live code
 * actually reaches (modules nothing imports are dead and do not count):
 *   Source.unused = true   evaluated, and no live code calls a capture API or imports a dedicated library
 *   Source.unused = false  a live call / dedicated import was found; Source.reached = Evidence[]
 *   Source.unused absent   not evaluated (no client code we can read, unknown language, or no API model for the kind)
 *   Source.declared        true when an Android permission / iOS usage key (not just a package) asked for it
 * A package-only hit (no permission declared) whose API is never reached collects nothing.
 *
 * Voice: web `getUserMedia({audio})` and mobile recording APIs make a microphone source; when the audio
 * reaches an AI vendor sink whose code streams or transcribes audio (realtime / live / transcription APIs),
 * `data:voice_video` is collected and flows to that sink.
 *
 * Exports `deadModules(ctx) → Set<rel>` (memoised in ctx.shared.deadModules) for other extractors/checks.
 * Graph edges whose every evidence item lies in a dead module get `deadCode: true` (annotation only).
 */

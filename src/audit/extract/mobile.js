// ---------------------------------------------------------------------------
// Dead-module detection (JS/TS family only). Conservative: a module is dead only when no other live file
// refers to its basename in any import/require specifier or config string, and it is not an entry by
// convention (route directories, root files, index/main/App/layout/page/config files).

const ENTRY_DIRS = new Set([
  'app', 'pages', 'routes', 'api', 'server', 'functions', 'scripts', 'bin', 'workers', 'worker', 'cron', 'jobs',
  'supabase', 'netlify', 'plugins', 'middleware', 'e2e', '__tests__', 'test', 'tests', '.storybook', 'stories',
  'public', 'static', 'edge', 'lambda', 'handlers', 'cli', 'commands', 'migrations', 'seeds', 'prisma', 'config',
  'src-tauri', 'electron', 'extension', 'background', 'content', 'popup', 'android', 'ios', 'web', 'docs', 'examples',
]);
const ENTRY_BASE = /^(index|main|app|_app|_document|_layout|layout|page|route|routes|server|client|entry[\w.-]*|root|router|middleware|worker|sw|service-worker|setup[\w.-]*|instrumentation|global[\w.-]*|\+[\w.-]+|[\w.-]+\.config|[\w.-]+\.d|[\w.-]+\.stories|[\w.-]+\.(test|spec))$/i;

function moduleKeys(rel) {
  const parts = rel.split('/');
  const file = parts[parts.length - 1];
  const base = file.replace(/\.[^.]+$/, '');
  const keys = new Set([base.toLowerCase(), base.replace(/\.(ios|android|web|native|server|client)$/i, '').toLowerCase()]);
  if (/^index$/i.test(base) && parts.length > 1) keys.add(parts[parts.length - 2].toLowerCase());
  return keys;
}

function specKey(spec) {
  const s = spec.replace(/[?#].*$/, '').replace(/\/+$/, '');
  const last = s.split('/').pop() || '';
  return last.replace(/\.(jsx?|tsx?|mjs|cjs|vue|svelte|astro)$/i, '').toLowerCase();
}

/** Set of rel paths of JS/TS modules that no live code imports. Memoised in ctx.shared.deadModules. */
export function deadModules(ctx) {
  ctx.shared = ctx.shared || {};
  if (ctx.shared.deadModules instanceof Set) return ctx.shared.deadModules;
  const dead = new Set();
  ctx.shared.deadModules = dead;
  const files = (ctx.files || []).filter((f) => f && typeof f.rel === 'string' && typeof f.content === 'string' && !f.test);
  const jsFiles = files.filter((f) => JS_EXT.test(f.rel));
  if (!jsFiles.length) return dead;
  // Glob/context imports and module-federation make references invisible to us: do not guess.
  if (jsFiles.some((f) => /\brequire\.context\s*\(|\bimport\.meta\.glob(Eager)?\s*\(/.test(f.content))) return dead;

  const refsByKey = new Map(); // key → Set<referring rel>
  let internal = 0;
  for (const f of jsFiles) {
    for (const s of specifiers(f.content)) {
      if (/^(\.|@\/|~\/|#|src\/|@src\/|@app\/|@lib\/|@components\/)/.test(s)) internal++;
      const k = specKey(s);
      if (!k) continue;
      if (!refsByKey.has(k)) refsByKey.set(k, new Set());
      refsByKey.get(k).add(f.rel);
    }
  }
  if (internal < 5) return dead; // import scanning does not see this codebase's module style
  // Config/markup files can name modules (app.json "main", plugin paths, <script src>); docs cannot.
  const otherText = files.filter((f) => /\.(json|ya?ml|toml|html?|xml)$/i.test(f.rel)).map((f) => f.content).join('\n');

  const candidates = new Map(); // rel → Set<referrer rel>
  for (const f of jsFiles) {
    const parts = f.rel.split('/');
    if (parts.length < 2) continue;
    if (parts.slice(0, -1).some((d) => ENTRY_DIRS.has(d.toLowerCase()) || /^\(.*\)$|^\[.*\]$/.test(d))) continue;
    const base = parts[parts.length - 1].replace(/\.[^.]+$/, '');
    if (ENTRY_BASE.test(base)) continue;
    const keys = moduleKeys(f.rel);
    const referrers = new Set();
    let external = false;
    for (const k of keys) {
      for (const r of refsByKey.get(k) || []) if (r !== f.rel) referrers.add(r);
      const esc = k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      if (otherText && new RegExp(`[/'"\`]${esc}(\\.[a-z]+)?['"\`]`, 'i').test(otherText)) external = true;
    }
    if (external) continue;
    candidates.set(f.rel, referrers);
  }
  let changed = true;
  while (changed) {
    changed = false;
    for (const [rel, referrers] of candidates) {
      if (dead.has(rel)) continue;
      if ([...referrers].every((r) => dead.has(r))) {
        dead.add(rel);
        changed = true;
      }
    }
  }
  return dead;
}


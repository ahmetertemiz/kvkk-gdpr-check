/** Placeholder helper: value or [[label]]. */
export function P(value, label) {
  if (value === undefined || value === null || value === '' || value === false) return `[[${label}]]`;
  return String(value);
}

const esc = (v) => String(v ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

export function mdTable(headers, rows) {
  if (!rows.length) return '';
  return [
    `| ${headers.map(esc).join(' | ')} |`,
    `|${headers.map(() => '---').join('|')}|`,
    ...rows.map((r) => `| ${r.map(esc).join(' | ')} |`),
  ].join('\n');
}

export function toCsv(headers, rows) {
  const q = (v) => {
    const s = String(v ?? '');
    return /[",;\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  return '﻿' + [headers, ...rows].map((r) => r.map(q).join(',')).join('\r\n') + '\r\n';
}

export const L = (label, lang) => (!label ? '' : typeof label === 'string' ? label : label[lang] || label.en);

export function today() {
  return new Date().toISOString().slice(0, 10);
}

/** Join non-empty sections with blank lines. */
export const join = (...parts) => parts.flat().filter((p) => p !== null && p !== undefined && p !== '').join('\n\n') + '\n';

export function header(lang, facts, title) {
  const src = [facts.source.dir && (lang === 'tr' ? 'kaynak kod' : 'source code'), facts.source.url].filter(Boolean).join(' + ');
  const note =
    lang === 'tr'
      ? `> Bu belge **kvkk-gdpr-check** tarafından ${facts.date} tarihinde ${src} taramasına göre otomatik oluşturulmuştur. **Hukuki danışmanlık değildir**; yayımlamadan önce bir avukata/KVKK uzmanına kontrol ettirin. \`[[...]]\` ile işaretli alanları doldurun, \`[[kontrol: ...]]\` notlarını doğrulayın.`
      : `> Generated by **kvkk-gdpr-check** on ${facts.date} from a scan of ${src}. **This is not legal advice** — have it reviewed by a lawyer before publishing. Fill in every \`[[...]]\` and verify every \`[[check: ...]]\`.`;
  return `# ${title}\n\n${note}`;
}

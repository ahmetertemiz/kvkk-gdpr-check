export function esc(s) {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

const arr = (x) => (Array.isArray(x) ? x : []);

function scoreColor(score) {
  if (score >= 75) return 'var(--good)';
  if (score >= 50) return 'var(--warn)';
  return 'var(--bad)';
}

function gauge(score, t) {
  const r = 52;
  const c = 2 * Math.PI * r;
  const pct = Math.max(0, Math.min(100, score)) / 100;
  const grade = scoreGrade(score);
  return `<div class="gauge" role="img" aria-label="${esc(t.score)}: ${score}/100">
  <svg viewBox="0 0 120 120" width="148" height="148" aria-hidden="true">
    <circle cx="60" cy="60" r="${r}" fill="none" stroke="var(--track)" stroke-width="12"/>
    <circle cx="60" cy="60" r="${r}" fill="none" stroke="${scoreColor(score)}" stroke-width="12" stroke-linecap="round"
      stroke-dasharray="${(c * pct).toFixed(2)} ${c.toFixed(2)}" transform="rotate(-90 60 60)"/>
  </svg>
  <div class="gauge-label"><span class="gauge-num">${score}</span><span class="gauge-sub">/100</span></div>
  <div class="grade" style="--gc:${scoreColor(score)}">${grade} · ${esc(t.gradeText[grade])}</div>
</div>`;
}

function locationList(f, t, lang) {
  const items = f.locations.slice(0, 50).map((l) => {
    const where = loc(l);
    const label = L(l.label, lang);
    const parts = [];
    if (label && label !== l.snippet) parts.push(`<span class="loc-label">${esc(label)}</span>`);
    if (where) {
      const isUrl = /^https?:\/\//i.test(where);
      parts.push(isUrl ? `<a class="loc-where" href="${esc(where)}" rel="noopener noreferrer" target="_blank">${esc(where)}</a>` : `<span class="loc-where">${esc(where)}</span>`);
    }
    if (l.count > 1) parts.push(`<span class="loc-count">${esc(t.times(l.count))}</span>`);
    if (!parts.length && !l.snippet) return '';
    return `<li>${parts.join(' ')}${l.snippet ? `<code class="snippet">${esc(l.snippet)}</code>` : ''}</li>`;
  });
  const more = f.locations.length > 50 ? `<li class="muted">+${f.locations.length - 50}</li>` : '';
  const body = items.filter(Boolean).join('') + more;
  return body ? `<div class="block"><h4>${esc(t.where)}</h4><ul class="locs">${body}</ul></div>` : '';
}

function findingCard(f, t, lang, idx) {
  const { rule, severity } = f;
  const cat = CATEGORIES[rule.category] ? rule.category : 'other';
  const catMeta = CATEGORIES[cat] || { tr: 'Diğer', en: 'Other', icon: '•' };
  const text = [rule.id, rule.title[lang], rule.desc[lang], ...f.locations.map((l) => `${loc(l) || ''} ${L(l.label, lang)}`)].join(' ').toLowerCase();
  return `<details class="finding sev-${severity}" data-sev="${severity}" data-cat="${esc(cat)}" data-text="${esc(text)}" id="f-${esc(rule.id)}"${idx < 3 && (severity === 'critical' || severity === 'high') ? ' open' : ''}>
  <summary>
    <span class="badge b-${severity}">${esc(SEV_LABEL[lang][severity])}</span>
    <span class="f-title">${esc(rule.title[lang])}</span>
    <span class="f-meta"><span class="f-cat">${catMeta.icon} ${esc(catMeta[lang])}</span><span class="f-id">${esc(rule.id)}</span><span class="f-n">${f.locations.length}</span></span>
  </summary>
  <div class="f-body">
    ${locationList(f, t, lang)}
    <div class="block"><h4>${esc(t.why)}</h4><p>${esc(rule.desc[lang])}</p></div>
    <div class="block fix"><h4>${esc(t.fix)}</h4><p>${esc(rule.fix[lang])}</p></div>
    <p class="refs">${esc(t.refs)}: ${rule.refs.map((r) => `<span>${esc(r)}</span>`).join('')}</p>${basisNote(rule, lang) ? `<p class="refs">⚠ ${esc(basisNote(rule, lang))}</p>` : ''}
  </div>
</details>`;
}

function categoryBars(result, lang) {
  const byCat = {};
  for (const f of result.findings) {
    const cat = CATEGORIES[f.rule.category] ? f.rule.category : 'other';
    (byCat[cat] ||= { n: 0, worst: 4 });
    byCat[cat].n++;
    byCat[cat].worst = Math.min(byCat[cat].worst, SEVS.indexOf(f.severity));
  }
  const cats = [...CATEGORY_ORDER, 'other'].filter((c) => byCat[c]);
  if (!cats.length) return '';
  const max = Math.max(...cats.map((c) => byCat[c].n));
  return cats
    .map((c) => {
      const meta = CATEGORIES[c] || { tr: 'Diğer', en: 'Other', icon: '•' };
      const w = Math.max(6, Math.round((byCat[c].n / max) * 100));
      return `<button type="button" class="cbar" data-cat-jump="${esc(c)}"><span class="cbar-name">${meta.icon} ${esc(meta[lang])}</span><span class="cbar-track"><span class="cbar-fill b-${SEVS[byCat[c].worst]}" style="width:${w}%"></span></span><span class="cbar-n">${byCat[c].n}</span></button>`;
    })
    .join('');
}

function cookieTable(cookies, t, lang) {
  cookies = arr(cookies);
  if (!cookies.length) return `<p class="muted">${esc(t.none)}</p>`;
  const rows = cookies
    .map((c) => {
      const ne = isNonEssentialCookie(c);
      const exp = c.expiresDays == null || c.expiresDays < 0 ? t.session : t.days(Math.round(c.expiresDays));
      const flags = [c.secure ? 'Secure' : null, c.httpOnly ? 'HttpOnly' : null, c.sameSite ? `SameSite=${c.sameSite}` : null].filter(Boolean).join(' · ');
      return `<tr class="${ne ? 'row-bad' : ''}"><td><code>${esc(c.name)}</code>${ne ? ` <span class="pill pill-bad">${esc(t.nonEssential)}</span>` : ''}</td><td>${esc(c.domain)}${c.firstParty === false ? ` <span class="pill">${esc(t.thirdPartyShort)}</span>` : c.firstParty ? ` <span class="pill">${esc(t.firstParty)}</span>` : ''}</td><td>${esc(c.vendorName || c.vendor || '—')}</td><td>${esc(c.category || '—')}</td><td>${esc(exp)}</td><td class="muted">${esc(flags || '—')}</td></tr>`;
    })
    .join('');
  return `<div class="table-wrap"><table><thead><tr><th>${esc(t.name)}</th><th>${esc(t.domain)}</th><th>${esc(t.vendor)}</th><th>${esc(t.category)}</th><th>${esc(t.expires)}</th><th>${esc(t.flags)}</th></tr></thead><tbody>${rows}</tbody></table></div>`;
}

function hostTable(hosts, t, withCountry = true) {
  hosts = arr(hosts);
  if (!hosts.length) return `<p class="muted">${esc(t.none)}</p>`;
  const rows = hosts
    .map((h) => `<tr><td><code>${esc(h.host)}</code></td><td>${esc(h.vendorName || h.vendor || '—')}</td><td>${esc(h.category || '—')}</td>${withCountry ? `<td>${esc(h.country || '—')}</td>` : ''}<td class="num">${esc(h.count ?? '')}</td></tr>`)
    .join('');
  return `<div class="table-wrap"><table><thead><tr><th>${esc(t.host)}</th><th>${esc(t.vendor)}</th><th>${esc(t.category)}</th>${withCountry ? `<th>${esc(t.country)}</th>` : ''}<th class="num">${esc(t.count)}</th></tr></thead><tbody>${rows}</tbody></table></div>`;
}

const check = (ok, label) => `<li class="${ok ? 'ok' : 'nok'}"><span class="mark" aria-hidden="true">${ok ? '✓' : '✗'}</span>${esc(label)}</li>`;

function liveSection(live, t, lang) {
  if (!live) return '';
  const ls = liveSummary(live);
  const parts = [];
  parts.push(`<div class="live-head"><div><span class="muted">${esc(t.site)}:</span> <a href="${esc(ls.url)}" rel="noopener noreferrer" target="_blank">${esc(ls.url)}</a></div>${live.mode ? `<div><span class="muted">${esc(t.mode)}:</span> ${esc(live.mode === 'browser' ? `${t.browserMode}${live.browser ? ` (${live.browser})` : ''}` : t.httpMode)}</div>` : ''}</div>`);

  const stat = (n, label, bad) => `<div class="lstat${bad ? ' lstat-bad' : ''}"><span class="lstat-n">${n}</span><span class="lstat-l">${esc(label)}</span></div>`;
  parts.push(`<div class="lstats">
    ${stat(ls.cookiesBefore.length, t.cookiesBefore, ls.nonEssentialBefore.length > 0)}
    ${stat(ls.thirdParty.length, t.thirdParty, false)}
    ${stat(arr(live.requestsBeforeConsent).length, t.requestsBefore, arr(live.requestsBeforeConsent).some((r) => ['analytics', 'marketing', 'session-replay'].includes(r.category)))}
    ${stat(ls.missingHeaders.length, t.headers + ' ✗', ls.missingHeaders.length > 2)}
  </div>`);

  const grid = [];
  if (live.banner) {
    const b = live.banner;
    grid.push(`<div class="card"><h3>${esc(t.banner)}</h3><ul class="checks">${check(b.found, t.bannerFound)}${check(b.hasAccept, t.hasAccept)}${check(b.hasReject, t.hasReject)}${check(b.rejectOnFirstLayer, t.rejectFirst)}${check(b.hasSettings, t.hasSettings)}</ul>${b.text ? `<blockquote>${esc(String(b.text).slice(0, 300))}</blockquote>` : ''}</div>`);
  }
  if (live.headers) {
    const h = live.headers;
    const items = Object.entries(HEADER_NAMES).filter(([k]) => k in h).map(([k, name]) => check(!!h[k], name)).join('');
    grid.push(`<div class="card"><h3>${esc(t.headers)}</h3><ul class="checks">${items}</ul></div>`);
  }
  if (live.privacyPageCheck) {
    const p = live.privacyPageCheck;
    grid.push(`<div class="card"><h3>${esc(t.privacyPage)}</h3>${p.url ? `<p class="muted small"><a href="${esc(p.url)}" rel="noopener noreferrer" target="_blank">${esc(p.url)}</a></p>` : ''}<ul class="checks">${arr(p.present).map((x) => check(true, x)).join('')}${arr(p.missing).map((x) => check(false, x)).join('')}</ul></div>`);
  }
  if (arr(live.privacyLinks).length || 'privacyLinks' in live) {
    const links = arr(live.privacyLinks);
    grid.push(`<div class="card"><h3>${esc(t.privacyLinks)}</h3>${links.length ? `<ul class="plain">${links.map((l) => `<li><span class="pill">${esc(l.kind || '')}</span> <a href="${esc(l.href)}" rel="noopener noreferrer" target="_blank">${esc(l.text || l.href)}</a></li>`).join('')}</ul>` : `<p class="bad-text">✗ ${esc(t.none)}</p>`}</div>`);
  }
  if (grid.length) parts.push(`<div class="grid2">${grid.join('')}</div>`);

  parts.push(`<div class="card"><h3>${esc(t.cookiesBefore)} <span class="count">${ls.cookiesBefore.length}</span></h3>${cookieTable(live.cookiesBeforeConsent, t, lang)}</div>`);
  if ('cookiesAfterReject' in live) parts.push(`<div class="card"><h3>${esc(t.cookiesAfterReject)} <span class="count">${arr(live.cookiesAfterReject).length}</span></h3>${cookieTable(live.cookiesAfterReject, t, lang)}</div>`);
  if ('cookiesAfterAccept' in live) parts.push(`<div class="card"><h3>${esc(t.cookiesAfterAccept)} <span class="count">${arr(live.cookiesAfterAccept).length}</span></h3>${cookieTable(live.cookiesAfterAccept, t, lang)}</div>`);
  if (arr(live.storageBeforeConsent).length) parts.push(`<div class="card"><h3>${esc(t.storage)}</h3><ul class="plain">${arr(live.storageBeforeConsent).map((s) => `<li><span class="pill">${esc(s.type)}</span> <code>${esc(s.key)}</code></li>`).join('')}</ul></div>`);
  if ('requestsBeforeConsent' in live) parts.push(`<div class="card"><h3>${esc(t.requestsBefore)}</h3>${hostTable(live.requestsBeforeConsent, t, false)}</div>`);
  parts.push(`<div class="card"><h3>${esc(t.thirdParty)} <span class="count">${ls.thirdParty.length}</span></h3>${hostTable(live.thirdPartyHosts, t, true)}</div>`);
  if (arr(live.forms).length) {
    parts.push(`<div class="card"><h3>${esc(t.forms)}</h3>${arr(live.forms)
      .map((f) => `<div class="form-item"><div><code>${esc((f.method || 'GET').toUpperCase())}</code> ${esc(f.action || '')} <span class="muted small">${esc(f.page || '')}</span></div><div class="small">${arr(f.fields).map((x) => `<span class="pill">${esc(x.name || '?')}:${esc(x.type || '')}</span>`).join(' ')}</div><ul class="checks small">${check(!arr(f.preChecked).length, `${t.preChecked}: ${arr(f.preChecked).join(', ') || t.none}`)}${check(!!f.hasPrivacyLinkNearby, t.privacyNearby)}</ul></div>`)
      .join('')}</div>`);
  }
  if (arr(live.pages).length) {
    parts.push(`<div class="card"><h3>${esc(t.pages)}</h3><ul class="plain">${arr(live.pages).map((p) => `<li><span class="pill">${esc(p.status ?? '')}</span> <a href="${esc(p.url)}" rel="noopener noreferrer" target="_blank">${esc(p.url)}</a> <span class="muted">${esc(p.title || '')}</span></li>`).join('')}</ul></div>`);
  }
  return parts.join('\n');
}


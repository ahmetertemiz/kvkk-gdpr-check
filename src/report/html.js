/**
 * Render a self-contained HTML report (no external requests).
 * @param {object} result  see src/summary.js
 * @param {{lang?:'tr'|'en'}} opts
 */
export function toHtml(result, { lang = 'tr' } = {}) {
  if (!S[lang]) lang = 'tr';
  const t = S[lang];
  const counts = result.counts || {};
  const date = new Date();
  const dateStr = date.toLocaleString(lang === 'tr' ? 'tr-TR' : 'en-GB', { dateStyle: 'medium', timeStyle: 'short' });
  const reportKey = (result.root || result.url || 'report').replace(/[^\w.:/-]/g, '').slice(-120);

  const meta = [];
  if (result.root) meta.push(`<span>${esc(t.project)}: <b>${esc(result.root)}</b></span>`);
  if (result.url) meta.push(`<span>${esc(t.site)}: <b>${esc(result.url)}</b></span>`);
  meta.push(`<span>${esc(t.date)}: <b>${esc(dateStr)}</b></span>`);
  if (result.filesScanned) meta.push(`<span><b>${esc(result.filesScanned)}</b> ${esc(t.files)}</span>`);

  const sevTiles = SEVS.map(
    (s) => `<button type="button" class="sev s-${s}" data-sev-filter="${s}" aria-pressed="false"><span class="sev-n">${counts[s] ?? 0}</span><span class="sev-l">${esc(SEV_LABEL[lang][s])}</span></button>`,
  ).join('');

  const presentCats = [...CATEGORY_ORDER, 'other'].filter((c) => result.findings.some((f) => (CATEGORIES[f.rule.category] ? f.rule.category : 'other') === c));
  const catChips =
    `<button type="button" class="chip" data-cat-filter="" aria-pressed="true">${esc(t.all)}</button>` +
    presentCats.map((c) => {
      const m = CATEGORIES[c] || { tr: 'Diğer', en: 'Other', icon: '•' };
      return `<button type="button" class="chip" data-cat-filter="${esc(c)}" aria-pressed="false">${m.icon} ${esc(m[lang])}</button>`;
    }).join('');

  const cards = result.findings.map((f, i) => findingCard(f, t, lang, i)).join('\n');
  const checklist = result.findings
    .filter((f) => f.severity !== 'info')
    .map(
      (f) => `<label class="cl-item"><input type="checkbox" value="${esc(f.rule.id)}"><span><span class="badge b-${f.severity}">${esc(SEV_LABEL[lang][f.severity])}</span> <span class="cl-title">${esc(f.rule.title[lang])}</span> <span class="f-id">${esc(f.rule.id)}</span><div class="cl-fix">${esc(f.rule.fix[lang])}</div></span></label>`,
    )
    .join('');

  const notice = supportNotice(result, lang, { quickScan: true });
  const hasLive = !!result.live;
  const bars = categoryBars(result, lang);

  return `<!doctype html>
<html lang="${lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="referrer" content="no-referrer">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; img-src data:; base-uri 'none'; form-action 'none'">
<title>${esc(t.title)} · ${result.score}/100</title>
<style>${CSS}</style>
</head>
<body data-report-key="${esc(reportKey)}">
<div class="wrap">
<header class="top">
  <div>
    <div class="brand">🛡️ kvkk-gdpr-check</div>
    <h1>${esc(t.title)}</h1>
    <div class="meta">${meta.join('')}</div>
  </div>
  <div class="actions"><button type="button" class="btn" id="print">${esc(t.print)}</button></div>
</header>

${notice ? `<div class="card" role="alert" style="border-left:4px solid #d97706;margin-bottom:14px"><b>⚠ ${esc(notice.text)}</b></div>` : ''}
<section class="hero">
  <div class="card">${gauge(result.score, t)}</div>
  <div class="card">
    <div class="sevs">${sevTiles}</div>
    ${bars ? `<h3>${esc(t.byCategory)}</h3>${bars}` : `<p class="muted">${esc(t.noFindings)}</p>`}
  </div>
</section>

<nav class="tabs" role="tablist">
  <button type="button" class="tab" role="tab" data-tab="findings" aria-selected="true">${esc(t.findings)} (${result.findings.length})</button>
  <button type="button" class="tab" role="tab" data-tab="checklist" aria-selected="false">${esc(t.checklist)}</button>
  ${hasLive ? `<button type="button" class="tab" role="tab" data-tab="live" aria-selected="false">🌐 ${esc(t.live)}</button>` : ''}
</nav>

<section class="panel" data-panel="findings" data-title="${esc(t.findings)}">
  ${result.findings.length ? `<div class="toolbar"><input id="search" class="search" type="search" placeholder="${esc(t.search)}" aria-label="${esc(t.search)}"><button type="button" class="btn" id="expand">${esc(t.expandAll)}</button><button type="button" class="btn" id="collapse">${esc(t.collapseAll)}</button></div>
  <div class="chips">${catChips}</div>` : ''}
  <div id="findings-list">${cards || `<div class="card empty">✅ ${esc(t.noFindings)}</div>`}</div>
  <div id="no-match" class="card empty" hidden>${esc(t.noMatch)}</div>
</section>

<section class="panel" data-panel="checklist" data-title="${esc(t.checklist)}" hidden>
  ${checklist ? `<div class="cl-head"><div class="progress"><span id="cl-progress"></span></div><span id="cl-count" class="muted" data-tpl="${esc(t.done('{a}', '{b}'))}"></span></div>
  <p class="muted small">${esc(t.checklistHint)}</p>${checklist}` : `<div class="card empty">✅ ${esc(t.noFindings)}</div>`}
</section>

${hasLive ? `<section class="panel" data-panel="live" data-title="${esc(t.live)}" hidden>${liveSection(result.live, t, lang)}</section>` : ''}

<footer>⚖️ ${esc(t.disclaimer)}<br>${esc(t.generated)} · ${esc(date.toISOString().slice(0, 10))}</footer>
</div>
<script>${JS}</script>
</body>
</html>
`;
}
